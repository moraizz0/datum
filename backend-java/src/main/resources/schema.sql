-- ===== USUÁRIOS: gravada pelo Java =====
-- "IF NOT EXISTS": roda a cada inicialização e só cria o que ainda não existe.
CREATE TABLE IF NOT EXISTS usuario (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       VARCHAR(120) NOT NULL,
  email      VARCHAR(160) NOT NULL UNIQUE,
  senha_hash VARCHAR(100) NOT NULL,
  perfil     VARCHAR(20)  NOT NULL DEFAULT 'USER'      CHECK (perfil IN ('USER','ADMIN')),
  status     VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE'  CHECK (status IN ('PENDENTE','APROVADO','BLOQUEADO')),
  criado_em  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ===== PLANILHA: gravadas pelo Python (analytics-python/banco.py) =====
-- Cada envio de planilha é um lote.
CREATE TABLE IF NOT EXISTS upload_lote (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  arquivo_nome     VARCHAR(200) NOT NULL,
  status           VARCHAR(20)  NOT NULL DEFAULT 'PROCESSANDO' CHECK (status IN ('PROCESSANDO','PROCESSADO','ERRO')),
  mensagem         VARCHAR(500),
  total_linhas     INTEGER      NOT NULL DEFAULT 0,
  linhas_validas   INTEGER      NOT NULL DEFAULT 0,
  linhas_invalidas INTEGER      NOT NULL DEFAULT 0,
  linhas_com_aviso INTEGER      NOT NULL DEFAULT 0,
  criado_em        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS consultor (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS servico (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS cliente (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lote_id           BIGINT        NOT NULL REFERENCES upload_lote(id) ON DELETE CASCADE,
  codigo_cti        VARCHAR(60)   NOT NULL,
  nome              VARCHAR(255)  NOT NULL,
  consultor_id      BIGINT        NOT NULL REFERENCES consultor(id),
  segmento          VARCHAR(40)   NOT NULL,
  nivel             VARCHAR(1)    NOT NULL CHECK (nivel IN ('A','B','C')),
  faturamento_anual NUMERIC(16,2) NOT NULL CHECK (faturamento_anual >= 0),
  cidade            VARCHAR(120),
  uf                VARCHAR(2),
  UNIQUE (lote_id, codigo_cti)
);
CREATE INDEX IF NOT EXISTS idx_cliente_lote ON cliente (lote_id);

-- Um contrato por serviço contratado de cada cliente.
CREATE TABLE IF NOT EXISTS contrato (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id       BIGINT NOT NULL REFERENCES cliente(id) ON DELETE CASCADE,
  servico_id       BIGINT NOT NULL REFERENCES servico(id),
  data_contratacao DATE   NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_contrato_cliente ON contrato (cliente_id);

-- O JSON do dashboard (médias, gráficos e frases) calculado pelo Python.
CREATE TABLE IF NOT EXISTS estatistica_lote (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lote_id   BIGINT    NOT NULL UNIQUE REFERENCES upload_lote(id) ON DELETE CASCADE,
  gerado_em TIMESTAMP NOT NULL,
  resultado TEXT      NOT NULL
);
